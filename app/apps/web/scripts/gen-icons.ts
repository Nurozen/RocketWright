/**
 * Generates `src/shell/icons.generated.ts` from `public/brand/icons/*.svg`
 * (the RocketWright line-icon set; see public/brand/PROVENANCE.md). Icons are inlined
 * so `stroke="currentColor"` follows the host's CSS colour (an `<img>` would
 * not inherit it).
 *
 * `node scripts/gen-icons.ts` writes; `--check` fails on drift.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";

export const ICON_DIR = resolve(import.meta.dirname, "../public/brand/icons");
export const ICON_MODULE = resolve(import.meta.dirname, "../src/shell/icons.generated.ts");

/** Inner markup of a 20x20 line icon, without its `<title>`; throws on an unexpected root. */
export function iconBody(svg: string, name: string): string {
  const m = /^\s*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(svg);
  if (!m) throw new Error(`${name}: not a single <svg> element`);
  const attrs = m[1]!;
  for (const want of ['viewBox="0 0 20 20"', 'fill="none"', 'stroke="currentColor"']) {
    if (!attrs.includes(want)) throw new Error(`${name}: root lacks ${want}`);
  }
  const body = m[2]!.replace(/<title>[\s\S]*?<\/title>/, "").trim();
  if (/<script|href=|<image|url\(/i.test(body)) throw new Error(`${name}: external reference or script`);
  return body;
}

/** The generated TypeScript module for the given `name.svg` files (sorted by name). */
export function buildIconModule(files: { name: string; svg: string }[]): string {
  const sorted = [...files].sort((a, b) => a.name.localeCompare(b.name));
  const lines = [
    "// Generated by `node scripts/gen-icons.ts` from public/brand/icons/*.svg. Do not edit.",
    "export const ICON_BODIES = {",
    ...sorted.map(({ name, svg }) => `  ${JSON.stringify(name)}: ${JSON.stringify(iconBody(svg, name))},`),
    "} as const;",
    "",
    "export type IconName = keyof typeof ICON_BODIES;",
    "",
  ];
  return lines.join("\n");
}

export function readIconFiles(dir = ICON_DIR): { name: string; svg: string }[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".svg"))
    .map((f) => ({ name: basename(f, ".svg"), svg: readFileSync(resolve(dir, f), "utf8") }));
}

function main(argv: string[]): number {
  const next = buildIconModule(readIconFiles());
  if (argv.includes("--check")) {
    const cur = readFileSync(ICON_MODULE, "utf8");
    if (cur !== next) {
      console.error("icons.generated.ts is stale: run `node scripts/gen-icons.ts`");
      return 1;
    }
    return 0;
  }
  writeFileSync(ICON_MODULE, next);
  return 0;
}

if (import.meta.main) process.exitCode = main(process.argv.slice(2));
