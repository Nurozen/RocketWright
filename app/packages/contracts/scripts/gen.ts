/**
 * TS generator for the published JSON Schemas (plan M1.6, invariant I3).
 *
 * Reads `schema/index.json` and every `schema/<name>.json` written by
 * `cargo xtask schema`, then writes `src/generated/`:
 * - `types.ts`: one TS declaration per Rust type (json-schema-to-typescript over
 *   a single bundle whose `definitions` merge every schema's `$defs` plus each
 *   registry root under its TS name, so shared types are declared once);
 * - `schema-meta.ts`: the `x-unit-dimension` / `x-expr` / `x-anchors` /
 *   `x-ui-group` metadata per type and field, plus the registry, tool, and
 *   resource lists;
 * - `index.ts`: re-exports both.
 *
 * Usage: `node scripts/gen.ts` writes; `node scripts/gen.ts --check` writes
 * nothing and exits 1 on drift (missing, changed, or stale generated files).
 * Only this script writes `src/generated/` (plan conventions).
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

type Json = null | boolean | number | string | Json[] | { [k: string]: Json };
type JsonObj = { [k: string]: Json };

export interface IndexEntry {
  name: string;
  file: string;
  iface: string;
  rust_type: string;
  ts_name: string;
}
export interface SchemaIndex {
  id_base: string;
  schema_version: string;
  entries: IndexEntry[];
  tools: { name: string; input: string; output: string; approval: string; hints: JsonObj }[];
  resources: { uri: string; type: string; subscribable: boolean }[];
}

const HERE = dirname(fileURLToPath(import.meta.url));
export const PACKAGE_DIR = resolve(HERE, "..");
export const REPO_ROOT = resolve(PACKAGE_DIR, "../../..");
export const SCHEMA_DIR = join(REPO_ROOT, "schema");
export const OUT_DIR = join(PACKAGE_DIR, "src/generated");

const BANNER = "// Generated by app/packages/contracts/scripts/gen.ts from schema/ (cargo xtask schema). Do not edit.";

/** Keywords that only constrain values, never the TS shape. */
const VALUE_ONLY = new Set([
  "description",
  "title",
  "maxLength",
  "minLength",
  "pattern",
  "propertyNames",
  "format",
  "minimum",
  "maximum",
  "exclusiveMinimum",
  "exclusiveMaximum",
  "multipleOf",
  "examples",
  "default",
  "$comment",
]);

function isObj(v: Json | undefined): v is JsonObj {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

/** Shape-relevant canonical text of a schema (for conflict detection). */
function shape(v: Json): string {
  const strip = (x: Json): Json => {
    if (Array.isArray(x)) return x.map(strip);
    if (!isObj(x)) return x;
    const out: JsonObj = {};
    for (const [k, val] of Object.entries(x)) {
      if (VALUE_ONLY.has(k) || k.startsWith("x-") || k === "$schema" || k === "$id" || k === "$defs") continue;
      out[k] = strip(val);
    }
    return out;
  };
  return JSON.stringify(strip(v));
}

/** Rewrites `#/$defs/X` refs to `#/definitions/X` (the bundle's layout). */
function relink(v: Json): Json {
  if (Array.isArray(v)) return v.map(relink);
  if (!isObj(v)) return v;
  const out: JsonObj = {};
  for (const [k, val] of Object.entries(v)) {
    if (k === "$ref" && typeof val === "string") out[k] = val.replace(/^#\/\$defs\//, "#/definitions/");
    else out[k] = relink(val);
  }
  return out;
}

/** Keywords that give a node its own shape next to a `$ref`. */
const SHAPE_KEYS = ["type", "properties", "required", "additionalProperties", "items", "anyOf", "oneOf", "allOf", "enum", "const"];

/** Name of the definition a `$ref` points at. */
function refName(ref: string): string {
  return ref.replace(/^#\/(\$defs|definitions)\//, "");
}

/**
 * Prepares one definition for an isolated compile: every `$ref` becomes
 * `tsType: <Name>` (so each type is declared exactly once, by its own
 * compile), and a `$ref` with shape siblings (a tagged variant:
 * `{$ref: NoseCone, properties: {type: {const: "nose_cone"}}}`) becomes
 * `allOf: [<Name>, {siblings}]`, i.e. `NoseCone & { type: "nose_cone" }`.
 * Inline titles are dropped so nested nodes never claim a declaration name.
 */
function isolate(v: Json, depth = 0): Json {
  if (Array.isArray(v)) return v.map((x) => isolate(x, depth + 1));
  if (!isObj(v)) return v;
  const out: JsonObj = {};
  for (const [k, val] of Object.entries(v)) {
    if (k === "title" && depth > 0) continue;
    if (k === "properties" && isObj(val)) {
      const props: JsonObj = {};
      for (const [pk, pv] of Object.entries(val)) props[pk] = isolate(pv, depth + 1);
      out[k] = props;
    } else out[k] = k === "$ref" ? val : isolate(val, depth + 1);
  }
  const ref = out.$ref;
  if (typeof ref !== "string") return out;
  delete out.$ref;
  const named: JsonObj = { tsType: refName(ref) };
  if (!SHAPE_KEYS.some((k) => k in out)) return { ...out, ...named };
  const rest: JsonObj = {};
  const keep: JsonObj = {};
  for (const [k, val] of Object.entries(out)) {
    if (SHAPE_KEYS.includes(k)) rest[k] = val;
    else keep[k] = val;
  }
  return { ...keep, allOf: [named, rest] };
}

export function readIndex(schemaDir = SCHEMA_DIR): SchemaIndex {
  return JSON.parse(readFileSync(join(schemaDir, "index.json"), "utf8")) as SchemaIndex;
}

function readSchema(schemaDir: string, file: string): JsonObj {
  return JSON.parse(readFileSync(join(schemaDir, file), "utf8")) as JsonObj;
}

/** Merges every schema's `$defs` and roots into one `definitions` map. */
export function bundle(index: SchemaIndex, schemaDir = SCHEMA_DIR): { definitions: Record<string, JsonObj>; roots: string[] } {
  const definitions: Record<string, JsonObj> = {};
  const origin: Record<string, string> = {};
  const conflicts: string[] = [];
  const put = (name: string, def: JsonObj, from: string) => {
    const prev = definitions[name];
    if (prev === undefined) {
      definitions[name] = def;
      origin[name] = from;
    } else if (shape(prev) !== shape(def)) {
      conflicts.push(`${name} (${origin[name]} vs ${from})`);
    }
  };
  const roots: string[] = [];
  for (const e of index.entries) {
    const s = readSchema(schemaDir, e.file);
    const defs = isObj(s.$defs) ? s.$defs : {};
    for (const [k, d] of Object.entries(defs)) if (isObj(d)) put(k, relink(d) as JsonObj, e.name);
    const root: JsonObj = {};
    for (const [k, v] of Object.entries(s)) if (k !== "$schema" && k !== "$id" && k !== "$defs") root[k] = v;
    root.title = e.ts_name;
    put(e.ts_name, relink(root) as JsonObj, e.name);
    if (!roots.includes(e.ts_name)) roots.push(e.ts_name);
  }
  if (conflicts.length > 0) {
    throw new Error(`schema definitions with one name but different shapes:\n  ${conflicts.join("\n  ")}`);
  }
  return { definitions, roots };
}

const COMPILE_OPTIONS = {
  bannerComment: "",
  additionalProperties: false,
  unreachableDefinitions: false,
  declareExternallyReferenced: true,
  format: true,
  strictIndexSignatures: true,
  style: { printWidth: 120, singleQuote: false, trailingComma: "all" as const },
};

async function typesTs(index: SchemaIndex, schemaDir: string): Promise<string> {
  const { definitions, roots } = bundle(index, schemaDir);
  const names = Object.keys(definitions).sort();
  const parts: string[] = [BANNER, ""];
  const declared = new Set<string>();
  for (const name of names) {
    const def = { ...(isolate(definitions[name] as JsonObj) as JsonObj), title: name };
    const ts = await compile(def as never, name, { ...COMPILE_OPTIONS, cwd: schemaDir });
    for (const m of ts.matchAll(/^export (?:type|interface|enum|const enum) ([A-Za-z_][A-Za-z0-9_]*)\b/gm)) {
      const n = m[1] as string;
      if (declared.has(n) || (n !== name && names.includes(n))) {
        throw new Error(`generated declaration \`${n}\` (from ${name}) collides; give the Rust types distinct names`);
      }
      declared.add(n);
    }
    parts.push(ts.trim(), "");
  }
  parts.push("/** Any registry root type (schema/index.json). */");
  parts.push(`export type RwContract =\n${roots.map((r) => `  | ${r}`).join("\n")};`, "");
  return parts.join("\n");
}

export interface FieldMeta {
  unitDimension?: string;
  expr?: boolean;
  uiGroup?: string;
  anchors?: string[];
  ref?: string;
}
export interface TypeMeta {
  uiGroup?: string;
  anchors?: string[];
  fields?: Record<string, FieldMeta>;
  variants?: Record<string, { ref?: string; anchors?: string[] }>;
}

/** x- metadata of one schema node: own keys first, then through anyOf/oneOf/allOf. */
function nodeMeta(node: Json): FieldMeta {
  const m: FieldMeta = {};
  const visit = (n: Json, depth: number) => {
    if (!isObj(n) || depth > 4) return;
    const dim = n["x-unit-dimension"];
    if (m.unitDimension === undefined && typeof dim === "string") m.unitDimension = dim;
    if (m.expr === undefined && n["x-expr"] === true) m.expr = true;
    const ui = n["x-ui-group"];
    if (m.uiGroup === undefined && typeof ui === "string") m.uiGroup = ui;
    const anchors = n["x-anchors"];
    if (m.anchors === undefined && Array.isArray(anchors)) m.anchors = anchors.map(String);
    const ref = n.$ref;
    if (m.ref === undefined && typeof ref === "string") m.ref = ref.replace(/^#\/(\$defs|definitions)\//, "");
    for (const k of ["anyOf", "oneOf", "allOf"]) {
      const branches = n[k];
      if (Array.isArray(branches)) for (const b of branches) visit(b, depth + 1);
    }
  };
  visit(node, 0);
  return m;
}

function typeMeta(def: JsonObj): TypeMeta | undefined {
  const t: TypeMeta = {};
  if (typeof def["x-ui-group"] === "string") t.uiGroup = def["x-ui-group"];
  if (Array.isArray(def["x-anchors"])) t.anchors = def["x-anchors"].map(String);
  const fields: Record<string, FieldMeta> = {};
  if (isObj(def.properties)) {
    for (const [k, p] of Object.entries(def.properties)) {
      const m = nodeMeta(p);
      if (m.unitDimension !== undefined || m.expr !== undefined || m.uiGroup !== undefined || m.anchors !== undefined) {
        fields[k] = m;
      }
    }
  }
  if (Object.keys(fields).length > 0) t.fields = fields;
  const variants: Record<string, { ref?: string; anchors?: string[] }> = {};
  for (const k of ["oneOf", "anyOf"]) {
    const branches = def[k];
    if (!Array.isArray(branches)) continue;
    for (const b of branches) {
      if (!isObj(b) || !isObj(b.properties)) continue;
      const tag = Object.values(b.properties).find((p): p is JsonObj => isObj(p) && typeof p.const === "string");
      if (tag === undefined || !Array.isArray(b["x-anchors"])) continue;
      const v: { ref?: string; anchors?: string[] } = { anchors: b["x-anchors"].map(String) };
      if (typeof b.$ref === "string") v.ref = b.$ref.replace(/^#\/(\$defs|definitions)\//, "");
      variants[tag.const as string] = v;
    }
  }
  if (Object.keys(variants).length > 0) t.variants = variants;
  return Object.keys(t).length > 0 ? t : undefined;
}

function schemaMetaTs(index: SchemaIndex, schemaDir: string): string {
  const { definitions } = bundle(index, schemaDir);
  const meta: Record<string, TypeMeta> = {};
  for (const k of Object.keys(definitions).sort()) {
    const m = typeMeta(definitions[k] as JsonObj);
    if (m !== undefined) meta[k] = m;
  }
  const registry = index.entries.map((e) => ({ name: e.name, file: e.file, iface: e.iface, tsName: e.ts_name }));
  const j = (v: unknown) => JSON.stringify(v, null, 2);
  return `${BANNER}
// x- metadata (R2.11) per generated type, for schema-driven editors and agents.

/** Metadata of one field. */
export interface FieldMeta {
  /** \`x-unit-dimension\`: the field's physical dimension (\`length\`, \`mass\`, ...). */
  readonly unitDimension?: string;
  /** \`x-expr\`: the field accepts \`=\` expressions. */
  readonly expr?: boolean;
  /** \`x-ui-group\`: the editor group. */
  readonly uiGroup?: string;
  /** \`x-anchors\`: named anchors. */
  readonly anchors?: readonly string[];
  /** Name of the referenced generated type, when the field is a \`$ref\`. */
  readonly ref?: string;
}

/** Metadata of one generated type. */
export interface TypeMeta {
  readonly uiGroup?: string;
  readonly anchors?: readonly string[];
  readonly fields?: Readonly<Record<string, FieldMeta>>;
  /** Tagged variants (e.g. component \`type\`): their type and anchors. */
  readonly variants?: Readonly<Record<string, { readonly ref?: string; readonly anchors?: readonly string[] }>>;
}

/** The JSON contract version (D19c). */
export const GENERATED_SCHEMA_VERSION = ${j(index.schema_version)} as const;

/** Base of every schema \`$id\`. */
export const SCHEMA_ID_BASE = ${j(index.id_base)} as const;

/** Types that carry x- metadata, keyed by generated type name. */
export const SCHEMA_META: Readonly<Record<string, TypeMeta>> = ${j(meta)};

/** Every published schema (\`schema/<file>\`) and its generated type. */
export const SCHEMA_REGISTRY = ${j(registry)} as const;

/** The MCP tool surface (\`rocketwright mcp\`). */
export const MCP_TOOL_CATALOG = ${j(index.tools)} as const;

/** MCP resources and the registry type each serves. */
export const MCP_RESOURCE_CATALOG = ${j(index.resources)} as const;
`;
}

const INDEX_TS = `${BANNER}
export type * from "./types.ts";
export * from "./schema-meta.ts";
`;

/** Every generated file, keyed by path relative to `src/generated/`. */
export async function generate(schemaDir = SCHEMA_DIR): Promise<Map<string, string>> {
  const index = readIndex(schemaDir);
  const out = new Map<string, string>();
  out.set("types.ts", await typesTs(index, schemaDir));
  out.set("schema-meta.ts", schemaMetaTs(index, schemaDir));
  out.set("index.ts", INDEX_TS);
  return out;
}

/** Drift between `outDir` and `files` (empty = current). */
export function drift(files: Map<string, string>, outDir = OUT_DIR): string[] {
  const problems: string[] = [];
  for (const [rel, text] of files) {
    const p = join(outDir, rel);
    if (!existsSync(p)) problems.push(`src/generated/${rel} is missing`);
    else if (readFileSync(p, "utf8") !== text) problems.push(`src/generated/${rel} differs`);
  }
  if (existsSync(outDir)) {
    for (const f of readdirSync(outDir)) {
      if (!files.has(f)) problems.push(`src/generated/${f} is stale`);
    }
  }
  return problems;
}

export function write(files: Map<string, string>, outDir = OUT_DIR): number {
  mkdirSync(outDir, { recursive: true });
  let n = 0;
  for (const [rel, text] of files) {
    const p = join(outDir, rel);
    if (existsSync(p) && readFileSync(p, "utf8") === text) continue;
    writeFileSync(p, text);
    n++;
  }
  for (const f of readdirSync(outDir)) {
    if (!files.has(f)) {
      rmSync(join(outDir, f), { recursive: true });
      n++;
    }
  }
  return n;
}

async function main(argv: string[]): Promise<number> {
  const check = argv.includes("--check");
  const files = await generate();
  if (check) {
    const problems = drift(files);
    if (problems.length === 0) {
      console.log(`gen:check: ${files.size} generated files current`);
      return 0;
    }
    for (const p of problems) console.error(`contracts drift: ${p}`);
    console.error("run `pnpm --filter @rw/contracts gen` (after `cargo xtask schema`) and commit src/generated/");
    return 1;
  }
  const n = write(files);
  console.log(`gen: wrote ${files.size} files (${n} changed)`);
  return 0;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main(process.argv.slice(2));
}
