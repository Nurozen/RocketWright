//! IF4 `ThrustCurve` and `MotorSource`. Internal values are SI.

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

/// A solid motor's thrust curve plus its header data.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct ThrustCurve {
    /// Designation, e.g. `C6`.
    pub designation: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub manufacturer: Option<String>,
    /// Impulse class letter (`A`..`O`).
    #[schemars(extend("pattern" = "^[1-9]?/?[0-9]*[A-O]$"))]
    pub class: String,
    #[schemars(extend("x-unit-dimension" = "length"))]
    pub diameter: f64,
    #[schemars(extend("x-unit-dimension" = "length"))]
    pub length: f64,
    /// Available ejection delays; empty = plugged only.
    #[schemars(extend("x-unit-dimension" = "time"))]
    pub delays: Vec<f64>,
    #[schemars(extend("x-unit-dimension" = "mass"))]
    pub prop_mass: f64,
    /// Total loaded mass at ignition.
    #[schemars(extend("x-unit-dimension" = "mass"))]
    pub total_mass: f64,
    #[schemars(extend("x-unit-dimension" = "impulse"))]
    pub total_impulse: f64,
    #[schemars(extend("x-unit-dimension" = "time"))]
    pub burn_time: f64,
    #[schemars(extend("x-unit-dimension" = "force"))]
    pub average_thrust: f64,
    #[schemars(extend("x-unit-dimension" = "force"))]
    pub max_thrust: f64,
    /// Samples, `t` ascending, starting at `t = 0`.
    pub points: Vec<ThrustPoint>,
    /// sha256 hex of the source file bytes (the motor digest).
    #[schemars(extend("pattern" = "^[0-9a-f]{64}$"))]
    pub sha256: String,
    pub source: MotorSource,
}

#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct ThrustPoint {
    #[schemars(extend("x-unit-dimension" = "time"))]
    pub t: f64,
    #[schemars(extend("x-unit-dimension" = "force"))]
    pub thrust: f64,
    /// Total motor mass at `t` (`.rse` only).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[schemars(extend("x-unit-dimension" = "mass"))]
    pub mass: Option<f64>,
    /// CG from the motor's fore end (`.rse` only).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[schemars(extend("x-unit-dimension" = "length"))]
    pub cg: Option<f64>,
}

/// Where a curve came from (motor provenance; never OR-DB curves, S:31).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum MotorSource {
    /// Built-in RocketWright generic curve (`lib/motors/generic/`), e.g. `RW_C6G`.
    Generic { id: String },
    /// A project `lib/motors/` file with its recorded sha256.
    Library { path: String },
    /// Embedded in an imported file (e.g. an `.rse` inside an `.ork`).
    Embedded { origin: String },
    /// ThrustCurve.org download in the gitignored cache (parity only).
    Thrustcurve { motor_id: String },
    /// Generated by a liquid engine design (`engines/<id>.rw.toml`).
    Liquid { engine: String },
}

/// A motor placed in a mount for one configuration.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct MountedMotor {
    /// Inner-tube id.
    pub mount: String,
    pub curve: ThrustCurve,
    /// Station of the motor's fore end.
    #[schemars(extend("x-unit-dimension" = "length"))]
    pub x_fore: f64,
    /// Ignition time after launch.
    #[schemars(extend("x-unit-dimension" = "time"))]
    pub ignition_time: f64,
    /// Selected ejection delay; `None` = plugged.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[schemars(extend("x-unit-dimension" = "time"))]
    pub delay: Option<f64>,
    /// Number of motors in the mount (cluster instances).
    pub count: u32,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
pub struct MotorError {
    pub line: u32,
    pub message: String,
}
