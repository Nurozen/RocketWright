//! Generates the field → dimension table that `asserts` uses, from the
//! `x-unit-dimension` annotations of the IF2 schema, at build time (M1.32: so
//! the runtime, and the WASM module, carry no schemars code). New component
//! fields are covered without a hand-written table.
#![allow(clippy::disallowed_methods, clippy::disallowed_types)]

use std::collections::BTreeMap;
use std::fmt::Write as _;

use serde_json::Value;

fn collect(v: &Value, out: &mut BTreeMap<String, String>) {
    match v {
        Value::Object(o) => {
            if let Some(Value::Object(props)) = o.get("properties") {
                for (k, p) in props {
                    if let Some(d) = p.get("x-unit-dimension").and_then(Value::as_str) {
                        out.entry(k.clone()).or_insert_with(|| d.to_string());
                    }
                }
            }
            o.values().for_each(|x| collect(x, out));
        }
        Value::Array(a) => a.iter().for_each(|x| collect(x, out)),
        _ => {}
    }
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    let schema = schemars::schema_for!(rw_model::EvaluatedModel);
    let v = serde_json::to_value(&schema).expect("IF2 schema as JSON");
    let mut dims = BTreeMap::new();
    collect(&v, &mut dims);
    let mut src = String::from(
        "/// Field name → `x-unit-dimension` name (generated by build.rs).\n\
         pub(crate) const FIELD_DIMS: &[(&str, &str)] = &[\n",
    );
    for (k, d) in &dims {
        writeln!(src, "    ({k:?}, {d:?}),").expect("write");
    }
    src.push_str("];\n");
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out.join("field_dims.rs"), src).expect("write field_dims.rs");
}
