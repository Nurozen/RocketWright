//! `cargo xtask schema [--check]`: the schema pipeline (plan M1.6, invariant I3).
//!
//! Writes, from `rw_api::schema_registry()`:
//! - `schema/<name>.json` for every registry entry (`schema/tools/<tool>.input.json`, ...),
//!   pretty-printed with a trailing newline;
//! - `schema/index.json`: name, file, interface, Rust type, and TS name per entry
//!   (the TS generator in `app/packages/contracts/scripts/gen.ts` reads it);
//! - `schema/testdata/{refs,units,exprs,patches}.json`: shared vectors for the
//!   Rust parsers (M1.20, M1.21, M1.23) and their TS counterparts.
//!
//! Every vector's `schema_valid` flag is checked against the published
//! schema it belongs to before anything is written, so the vectors and the
//! schemas cannot disagree.
//!
//! `--check` writes nothing; it exits 1 when any file differs, is missing, or is
//! stale (a `schema/` file the registry no longer produces).

mod testdata;

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use serde_json::{Value, json};

/// Generated files, keyed by path relative to `schema/`.
pub type Files = BTreeMap<String, String>;

pub fn main(args: &[String]) -> ExitCode {
    let mut check = false;
    let mut root: Option<PathBuf> = None;
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--check" => check = true,
            "--root" => root = it.next().map(PathBuf::from),
            other => {
                eprintln!("xtask schema: unknown argument `{other}`");
                eprintln!("usage: cargo xtask schema [--check] [--root <repo>]");
                return ExitCode::from(2);
            }
        }
    }
    let dir = root.unwrap_or_else(crate::audit::repo_root).join("schema");
    let files = match generate() {
        Ok(f) => f,
        Err(e) => {
            eprintln!("xtask schema: {e}");
            return ExitCode::FAILURE;
        }
    };
    if check {
        let drift = diff(&dir, &files);
        if drift.is_empty() {
            println!("xtask schema --check: {} files current", files.len());
            ExitCode::SUCCESS
        } else {
            for d in &drift {
                eprintln!("schema drift: {d}");
            }
            eprintln!("run `cargo xtask schema` and commit schema/");
            ExitCode::FAILURE
        }
    } else {
        match write(&dir, &files) {
            Ok(n) => {
                println!("xtask schema: wrote {} files ({n} changed)", files.len());
                ExitCode::SUCCESS
            }
            Err(e) => {
                eprintln!("xtask schema: {e}");
                ExitCode::FAILURE
            }
        }
    }
}

/// Pretty JSON with a trailing newline (the `schema/` file format).
pub fn pretty(v: &Value) -> String {
    let mut s = serde_json::to_string_pretty(v).expect("JSON value serializes");
    s.push('\n');
    s
}

/// The TS type name for a Rust type path (`rw_model::RocketDoc` → `RocketDoc`).
pub fn ts_name(rust_type: &str) -> String {
    rust_type
        .rsplit("::")
        .next()
        .unwrap_or(rust_type)
        .trim()
        .to_string()
}

/// Every generated file, in memory.
pub fn generate() -> Result<Files, String> {
    let mut files = Files::new();
    let mut index = Vec::new();
    for e in rw_api::schema_registry() {
        let schema = e.schema();
        let v = schema.as_value();
        jsonschema::validator_for(v).map_err(|err| format!("{}: {err}", e.name))?;
        files.insert(e.file(), pretty(v));
        index.push(json!({
            "name": e.name,
            "file": e.file(),
            "iface": format!("{:?}", e.iface).to_uppercase(),
            "rust_type": e.rust_type,
            "ts_name": ts_name(e.rust_type),
        }));
    }
    let resources: Vec<Value> = rw_api::RESOURCES
        .iter()
        .map(|r| json!({"uri": r.uri, "type": r.type_name, "subscribable": r.subscribable}))
        .collect();
    let tools: Vec<Value> = rw_api::COMMANDS
        .iter()
        .filter(|d| d.mcp)
        .map(|d| {
            json!({
                "name": d.name,
                "input": format!("tools/{}.input", d.name),
                "output": format!("tools/{}.output", d.name),
                "approval": d.approval,
                "hints": d.hints,
            })
        })
        .collect();
    files.insert(
        "index.json".into(),
        pretty(&json!({
            "$comment": "Generated by `cargo xtask schema`; do not edit.",
            "id_base": rw_api::SCHEMA_ID_BASE,
            "schema_version": rw_api::contracts::SCHEMA_VERSION,
            "entries": index,
            "tools": tools,
            "resources": resources,
        })),
    );
    for (name, doc) in testdata::all()? {
        files.insert(format!("testdata/{name}.json"), pretty(&doc));
    }
    Ok(files)
}

/// Every `*.json` file under `dir`, relative, `/`-separated.
fn existing(dir: &Path) -> Vec<String> {
    fn walk(base: &Path, d: &Path, out: &mut Vec<String>) {
        let Ok(rd) = std::fs::read_dir(d) else { return };
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                walk(base, &p, out);
            } else if p.extension().is_some_and(|x| x == "json")
                && let Ok(rel) = p.strip_prefix(base)
            {
                out.push(rel.to_string_lossy().replace('\\', "/"));
            }
        }
    }
    let mut out = Vec::new();
    walk(dir, dir, &mut out);
    out.sort();
    out
}

/// Differences between `dir` and `files` (empty = current).
pub fn diff(dir: &Path, files: &Files) -> Vec<String> {
    let mut out = Vec::new();
    for (rel, text) in files {
        match std::fs::read_to_string(dir.join(rel)) {
            Ok(t) if &t == text => {}
            Ok(_) => out.push(format!("schema/{rel} differs")),
            Err(_) => out.push(format!("schema/{rel} is missing")),
        }
    }
    for rel in existing(dir) {
        if !files.contains_key(&rel) {
            out.push(format!(
                "schema/{rel} is stale (not produced by the registry)"
            ));
        }
    }
    out
}

/// Writes `files` under `dir` and removes stale `*.json`. Returns the number of
/// files created, changed, or removed.
pub fn write(dir: &Path, files: &Files) -> Result<usize, String> {
    let mut n = 0;
    for (rel, text) in files {
        let p = dir.join(rel);
        if std::fs::read_to_string(&p).ok().as_deref() == Some(text.as_str()) {
            continue;
        }
        if let Some(parent) = p.parent() {
            std::fs::create_dir_all(parent).map_err(|e| format!("{}: {e}", parent.display()))?;
        }
        std::fs::write(&p, text).map_err(|e| format!("{}: {e}", p.display()))?;
        n += 1;
    }
    for rel in existing(dir) {
        if !files.contains_key(&rel) {
            let p = dir.join(&rel);
            std::fs::remove_file(&p).map_err(|e| format!("{}: {e}", p.display()))?;
            n += 1;
        }
    }
    Ok(n)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ts_names() {
        assert_eq!(ts_name("rw_model::RocketDoc"), "RocketDoc");
        assert_eq!(ts_name("crate::Command"), "Command");
        assert_eq!(ts_name("MutationOut"), "MutationOut");
    }

    #[test]
    fn generation_is_deterministic_and_complete() {
        let a = generate().unwrap();
        let b = generate().unwrap();
        assert_eq!(a, b);
        for e in rw_api::schema_registry() {
            assert!(a.contains_key(&e.file()), "{}", e.name);
        }
        for t in ["refs", "units", "exprs", "patches"] {
            assert!(a.contains_key(&format!("testdata/{t}.json")));
        }
        assert!(a.values().all(|t| t.ends_with("}\n")));
    }

    #[test]
    fn rocket_schema_enforces_units() {
        // M1.6 verify: the published rocket schema accepts {"od":"54 mm"} and rejects {"od":54}.
        let files = generate().unwrap();
        let rocket: Value = serde_json::from_str(&files["rocket.json"]).unwrap();
        let v = jsonschema::validator_for(&rocket).unwrap();
        let tube = |od: Value| json!({"c": {"body": {"type": "body_tube", "length": "300 mm", "od": od, "id": "52 mm"}}});
        assert!(v.is_valid(&tube(json!("54 mm"))));
        assert!(!v.is_valid(&tube(json!(54))));
    }

    #[test]
    fn check_detects_drift_and_stale_files() {
        let dir = std::env::temp_dir().join(format!("rw-xtask-schema-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        let mut files = Files::new();
        files.insert("a.json".into(), "{}\n".into());
        files.insert("tools/b.json".into(), "{}\n".into());
        assert_eq!(diff(&dir, &files).len(), 2, "missing files");
        assert_eq!(write(&dir, &files).unwrap(), 2);
        assert!(diff(&dir, &files).is_empty());
        std::fs::write(dir.join("a.json"), "{ }\n").unwrap();
        std::fs::write(dir.join("old.json"), "{}\n").unwrap();
        let d = diff(&dir, &files);
        assert!(d.iter().any(|x| x.contains("a.json differs")), "{d:?}");
        assert!(d.iter().any(|x| x.contains("old.json is stale")), "{d:?}");
        assert_eq!(write(&dir, &files).unwrap(), 2);
        assert!(diff(&dir, &files).is_empty());
        let _ = std::fs::remove_dir_all(&dir);
    }
}
