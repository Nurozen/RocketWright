/**
 * Generates the configurations, simulation, and manifest of `fixtures/case1/`
 * from the oracle files (plan M1.54b):
 *
 * - `configs/<config id>.rw.toml`: one per `case1.geometry.json` configuration,
 *   the file stem being the oracle's config id verbatim, so the golden's
 *   `config_id` names our configuration.
 * - `sims/<slug>.rw.toml`: one per geometry sim, written from the golden
 *   `conditions` block (rail, rod, site, atmosphere, wind, integrator), with the
 *   sim name verbatim, so the evaluated sim's `conditions_hash` equals the
 *   golden's (checked by `crates/rw-api/tests/fixtures.rs`).
 * - `rocketwright.toml`: the project name, and the golden's configuration as
 *   the default.
 *
 * `rocket.rw.toml` is hand-authored; `crates/rw-model/src/components/case1.rs`
 * checks every golden input against it.
 *
 * Usage: `node scripts/fixtures/case1-from-golden.ts [--check]`. `--check`
 * exits 1 when a generated file differs from the committed one.
 */
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { canonicalJson, conditionsHash } from "../bar/parity.ts";

export const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const FIXTURE_DIR = join(REPO_ROOT, "fixtures/case1");
const ORACLE_DIR = join(REPO_ROOT, "tests/oracle");
const GENERIC_DIR = join(REPO_ROOT, "lib/motors/generic");

const HEADER = "# Generated by scripts/fixtures/case1-from-golden.ts from tests/oracle/case1*.json. Do not edit.";

interface Conditions {
  rail_length_m: number;
  rod_angle_deg: number;
  rod_direction_deg: number;
  site_altitude_m: number;
  latitude_deg: number;
  longitude_deg: number;
  base_temperature_k: number;
  base_pressure_pa: number;
  atmosphere: string;
  geodetic: string;
  wind_speed_ms: number;
  wind_direction_deg: number;
  wind_turbulence: number;
  time_step_s: number;
  integrator: string;
  gravity?: unknown;
  launch_into_wind?: unknown;
}

interface GeoMotor {
  mount: string;
  designation: string;
  digest: string;
  delay_s: number | null;
}

interface Geometry {
  name: string;
  components: { name: string; type: string; fields: Record<string, unknown> }[];
  configurations: { id: string; name: string; motors: GeoMotor[] }[];
  sims: { name: string; config_id: string; conditions: Conditions; conditions_hash: string }[];
}

interface GoldenEvent {
  kind: string;
  t_s: number;
}

interface Golden {
  sim_name: string;
  config_id: string;
  conditions: Conditions;
  conditions_hash: string;
  events?: GoldenEvent[];
}

/** A number as written in a quantity: shortest round-trip form, never exponent notation. */
export function num(x: number): string {
  if (!Number.isFinite(x)) throw new Error(`non-finite number ${String(x)}`);
  const s = String(x);
  if (/e/i.test(s)) throw new Error(`number ${s} needs exponent notation`);
  return s;
}

const q = (x: number, unit: string): string => `"${num(x)} ${unit}"`;

/** `Simulation 5` → `simulation_5` (a valid id). */
export function slug(name: string): string {
  const s = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
  return /^[a-z]/.test(s) ? s : `sim_${s}`;
}

/** `[c.<id>]` → `name` of every component in a hand-authored rocket file. */
export function componentIdsByName(rocketToml: string): Map<string, string[]> {
  const out = new Map<string, string[]>();
  let id: string | null = null;
  for (const line of rocketToml.split("\n")) {
    const h = /^\[c\.([a-z][a-z0-9_]*)\]\s*$/.exec(line);
    if (h) {
      id = h[1] ?? null;
      continue;
    }
    if (line.startsWith("[")) id = null;
    const n = /^name\s*=\s*"([^"]*)"/.exec(line);
    if (id && n?.[1] !== undefined) out.set(n[1], [...(out.get(n[1]) ?? []), id]);
  }
  return out;
}

function uniqueId(ids: Map<string, string[]>, name: string): string {
  const found = ids.get(name) ?? [];
  if (found.length !== 1) throw new Error(`rocket.rw.toml: expected one component named "${name}", found ${String(found.length)}`);
  return found[0] as string;
}

/** The sim file from a golden `conditions` block (every field written, none defaulted). */
export function simToml(name: string, configId: string, c: Conditions): string {
  if (c.gravity !== undefined || c.launch_into_wind !== undefined) {
    throw new Error("conditions with gravity or launch_into_wind are not generated yet");
  }
  return [
    HEADER,
    "",
    `name = ${JSON.stringify(name)}`,
    `config = ${JSON.stringify(configId)}`,
    "",
    "[launch]",
    `rail_length = ${q(c.rail_length_m, "m")}`,
    `rod_angle = ${q(c.rod_angle_deg, "deg")}`,
    `rod_direction = ${q(c.rod_direction_deg, "deg")}`,
    `altitude = ${q(c.site_altitude_m, "m")}`,
    `latitude = ${q(c.latitude_deg, "deg")}`,
    `longitude = ${q(c.longitude_deg, "deg")}`,
    `geodetic = ${JSON.stringify(c.geodetic)}`,
    "",
    "[atmosphere]",
    `model = ${JSON.stringify(c.atmosphere)}`,
    `base_temperature = ${q(c.base_temperature_k, "K")}`,
    `base_pressure = ${q(c.base_pressure_pa, "Pa")}`,
    "",
    "[wind]",
    `speed = ${q(c.wind_speed_ms, "m/s")}`,
    `direction = ${q(c.wind_direction_deg, "deg")}`,
    `turbulence = ${num(c.wind_turbulence)}`,
    "",
    "[integrator]",
    `method = ${JSON.stringify(c.integrator)}`,
    `dt = ${q(c.time_step_s, "s")}`,
    "",
  ].join("\n");
}

const sha256File = (p: string): string => createHash("sha256").update(readFileSync(p)).digest("hex");

/** Every generated file, project-relative path → text. */
export function generate(): Map<string, string> {
  const geometry = JSON.parse(readFileSync(join(ORACLE_DIR, "case1.geometry.json"), "utf8")) as Geometry;
  const golden = JSON.parse(readFileSync(join(ORACLE_DIR, "case1-generic.json"), "utf8")) as Golden;
  const ids = componentIdsByName(readFileSync(join(FIXTURE_DIR, "rocket.rw.toml"), "utf8"));
  const files = new Map<string, string>();

  if (conditionsHash(golden.conditions) !== golden.conditions_hash) {
    throw new Error("case1-generic.json: conditions_hash does not recompute from conditions");
  }

  // Recovery: the golden deploys at the ejection charge; altitude and delay from the geometry.
  const chutes = geometry.components.filter((c) => c.type === "parachute" || c.type === "streamer");
  const events = golden.events ?? [];
  const tEject = events.find((e) => e.kind === "ejection_charge")?.t_s;
  const tDeploy = events.find((e) => e.kind === "recovery_device_deployment")?.t_s;
  if (tEject === undefined || tDeploy === undefined || Math.abs(tDeploy - tEject) > 0.01) {
    throw new Error("case1-generic.json: expected deployment at the ejection charge");
  }

  for (const cfg of geometry.configurations) {
    const lines = [HEADER, "", `name = ${JSON.stringify(cfg.name)}`];
    for (const m of cfg.motors) {
      const rse = join(GENERIC_DIR, `${m.designation}.rse`);
      if (!existsSync(rse) || sha256File(rse) !== m.digest) {
        throw new Error(`${cfg.id}: motor ${m.designation} digest does not match lib/motors/generic/${m.designation}.rse`);
      }
      lines.push("", `[motors.${uniqueId(ids, m.mount)}]`, `motor = "generic:${m.designation}"`);
      if (m.delay_s !== null) lines.push(`delay = ${q(m.delay_s, "s")}`);
    }
    for (const c of chutes) {
      lines.push("", `[deploy.${uniqueId(ids, c.name)}]`, `event = "ejection"`);
      const alt = c.fields["deploy_altitude_m"];
      if (typeof alt === "number") lines.push(`altitude = ${q(alt, "m")}`);
      const delay = c.fields["deploy_delay_s"];
      if (typeof delay === "number" && delay !== 0) lines.push(`delay = ${q(delay, "s")}`);
    }
    files.set(`configs/${cfg.id}.rw.toml`, `${lines.join("\n")}\n`);
  }

  for (const s of geometry.sims) {
    if (!geometry.configurations.some((c) => c.id === s.config_id)) throw new Error(`sim ${s.name}: unknown config ${s.config_id}`);
    if (conditionsHash(s.conditions) !== s.conditions_hash) throw new Error(`sim ${s.name}: conditions_hash does not recompute`);
    if (s.name === golden.sim_name && canonicalJson(s.conditions) !== canonicalJson(golden.conditions)) {
      throw new Error(`sim ${s.name}: geometry and golden conditions differ`);
    }
    files.set(`sims/${slug(s.name)}.rw.toml`, simToml(s.name, s.config_id, s.conditions));
  }
  if (!geometry.sims.some((s) => s.name === golden.sim_name && s.config_id === golden.config_id)) {
    throw new Error("case1.geometry.json has no sim matching the golden's sim_name and config_id");
  }

  files.set(
    "rocketwright.toml",
    [HEADER, "", "format = 1", `name = ${JSON.stringify(geometry.name)}`, `default_config = ${JSON.stringify(golden.config_id)}`, ""].join("\n"),
  );
  return files;
}

/** Differences between the generated files and `dir` (missing, changed, or stale generated files). */
export function diffAgainst(files: Map<string, string>, dir: string = FIXTURE_DIR): string[] {
  const out: string[] = [];
  for (const [rel, text] of files) {
    const p = join(dir, rel);
    if (!existsSync(p)) out.push(`missing ${rel}`);
    else if (readFileSync(p, "utf8") !== text) out.push(`changed ${rel}`);
  }
  for (const sub of ["configs", "sims"]) {
    const d = join(dir, sub);
    if (!existsSync(d)) continue;
    for (const f of readdirSync(d)) if (!files.has(`${sub}/${f}`)) out.push(`stale ${sub}/${f}`);
  }
  return out;
}

function main(argv: string[]): number {
  const files = generate();
  if (argv.includes("--check")) {
    const diffs = diffAgainst(files);
    for (const d of diffs) console.error(`fixtures/case1: ${d} (run node scripts/fixtures/case1-from-golden.ts)`);
    return diffs.length === 0 ? 0 : 1;
  }
  for (const [rel, text] of files) writeFileSync(join(FIXTURE_DIR, rel), text);
  console.log(`fixtures/case1: wrote ${String(files.size)} files`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
