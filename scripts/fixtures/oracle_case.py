#!/usr/bin/env python3
"""Re-authors oracle cases 2-7 as RocketWright projects (M2.1-M2.3 parity).

Reads only `tests/oracle/case<n>.geometry.json` and `case<n>-generic.json`
(numbers plus component names, the one-way-valve files) and writes
`fixtures/case<n>/`:

- `rocket.rw.toml`: every geometry component, placed at its oracle station
  (each child attaches to its parent's fore/inner anchor with the station
  difference as the offset; body components chain aft-to-fore), with its
  material density, roughness, cluster pattern, fin cross-section, and stage
  membership; a stage mass override (`stage_mass_override_kg` on the stage's
  first component, case 5) becomes `[stage.<id>] override`.
- `configs/<config id>.rw.toml`: the golden's configuration (generic curves
  only; the other configurations name curves we do not ship).
- `sims/<slug>.rw.toml`: the golden sim with every condition written, so its
  `conditions_hash` equals the golden's.
- `rocketwright.toml`.

Modelling choices that are not in the geometry are listed in
`fixtures/README.md` (case 2-7 rows) and `docs/dev/parity-log.md` (M2.1-M2.3).

Usage: `python3 -I scripts/fixtures/oracle_case.py [--check] [cases...]`
(default: 2-7). `--check` exits 1 when a generated file differs.
"""

import hashlib
import json
import math
import re
import sys
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ORACLE = ROOT / "tests" / "oracle"
GENERIC = ROOT / "lib" / "motors" / "generic"


def header(n):
    return (
        f"# Generated by scripts/fixtures/oracle_case.py from tests/oracle/case{n}*.json. "
        "Do not edit."
    )


def num(x):
    """Shortest round-trip decimal, never exponent notation."""
    if not math.isfinite(x):
        raise ValueError(f"non-finite {x}")
    if x == 0:
        return "0"
    s = format(Decimal(repr(float(x))), "f")
    if "." in s:
        s = s.rstrip("0").rstrip(".")
    return s


def q(x, unit):
    return f'"{num(x)} {unit}"'


def slug(name):
    s = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    s = s[:32].rstrip("_")
    return s if re.match(r"^[a-z]", s) else f"c_{s}"


def toml_str(s):
    return json.dumps(s, ensure_ascii=False)


INNER_PARENTS = {"inner_tube", "coupler", "nose_cone"}
AXIAL = {"nose_cone", "body_tube", "transition"}
SURFACE = {
    "trapezoidal_fin_set",
    "elliptical_fin_set",
    "freeform_fin_set",
    "tube_fin_set",
    "launch_lug",
    "rail_button",
}
START_ANCHOR = {
    "trapezoidal_fin_set": "root_le",
    "elliptical_fin_set": "root_le",
    "freeform_fin_set": "root_le",
    "tube_fin_set": "fore",
    "parachute": "attach",
    "streamer": "attach",
    "shock_cord": "attach",
    "rail_button": "mid",
}
CLUSTER_PRESETS = {2: "2-row", 3: "3-ring", 4: "4-square", 5: "5-cross", 6: "6-ring", 7: "7-hex"}
FIN_CROSS_SECTIONS = ("square", "rounded", "airfoil")
STAGE_IDS = {1: ["sustainer"], 2: ["sustainer", "booster"], 3: ["sustainer", "middle", "booster"]}


class Case:
    def __init__(self, n):
        self.n = n
        self.geo = json.loads((ORACLE / f"case{n}.geometry.json").read_text())
        self.golden = json.loads((ORACLE / f"case{n}-generic.json").read_text())
        self.comps = self.geo["components"]
        self.ids = self._ids()
        self.materials = {}
        self.notes = []

    # ---- ids ---------------------------------------------------------------
    def _ids(self):
        out, used = [], set()
        for c in self.comps:
            base = slug(c["name"]) or c["type"]
            i, cand = 1, base
            while cand in used:
                i += 1
                cand = f"{base}_{i}"
            used.add(cand)
            out.append(cand)
        return out

    def index_of_parent(self, k):
        p = self.comps[k]["parent"]
        if p is None:
            return None
        # The parent is the nearest earlier component with that name, else any.
        cands = [i for i, c in enumerate(self.comps) if c["name"] == p and i != k]
        before = [i for i in cands if i < k]
        if not cands:
            raise ValueError(f"case {self.n}: no parent {p!r} for {self.comps[k]['name']!r}")
        # Prefer the candidate whose span contains the child (same stage).
        st = self.comps[k]["fields"].get("stage", 0)
        same = [i for i in cands if self.comps[i]["fields"].get("stage", 0) == st]
        pool = same or cands
        x = self.comps[k]["x_fore_m"]
        inside = [
            i
            for i in pool
            if self.comps[i]["x_fore_m"] - 1e-9 <= x <= self.comps[i]["x_fore_m"] + self.comps[i]["length_m"] + 1e-9
        ]
        pick = (inside or [i for i in pool if i in before] or pool)
        return max(i for i in pick if i < k) if any(i < k for i in pick) else pick[0]

    # ---- materials -----------------------------------------------------------
    def material(self, c, kind, value):
        name = c.get("material") or c["type"]
        key = (slug(name) or "material")[:24].rstrip("_")
        unit = {"density": "kg/m^3", "surface_density": "kg/m^2", "line_density": "kg/m"}[kind]
        for k, (mk, mv, mn) in self.materials.items():
            if mk == kind and mv == value and mn == name:
                return k
        cand, i = key, 1
        while cand in self.materials:
            i += 1
            cand = f"{key}_{i}"
        self.materials[cand] = (kind, value, name)
        return cand

    # ---- rocket ----------------------------------------------------------------
    def stage_of(self, c):
        return int(c["fields"].get("stage", 0))

    def stages(self):
        return sorted({self.stage_of(c) for c in self.comps})

    def stage_id(self, s):
        return STAGE_IDS[len(self.stages())][s]

    def rocket(self):
        out = [
            f"# Oracle case {self.n} ({self.geo['name']!r}, generic-curve variant), re-authored",
            f"# from tests/oracle/case{self.n}.geometry.json by scripts/fixtures/oracle_case.py.",
            "# Do not edit; modelling choices are listed in fixtures/README.md.",
            "",
            f"name = {toml_str(self.geo['name'])}",
        ]
        stages = self.stages()
        for s in stages:
            first = next(
                k
                for k, c in enumerate(self.comps)
                if c["parent"] is None and self.stage_of(c) == s
            )
            ov = self.stage_override(self.comps[first])
            if len(stages) == 1 and ov is None:
                continue
            out += ["", f"[stage.{self.stage_id(s)}]", f"first = {toml_str(self.ids[first])}"]
            out.append(f"name = {toml_str(self.stage_id(s).capitalize())}")
            if ov is not None:
                out.append(ov)
        prev_axial = None
        for k, c in enumerate(self.comps):
            out += ["", f"[c.{self.ids[k]}]"]
            out += self.component(k, c, prev_axial)
            if c["parent"] is None:
                prev_axial = k
            if c["type"] == "body_tube" and c["fields"].get("motor_mount", 0) > 0.5:
                out += ["", f"[c.{self.mount_id(k)}]"] + self.virtual_mount(k, c)
        for name, (kind, value, label) in self.materials.items():
            unit = {"density": "kg/m^3", "surface_density": "kg/m^2", "line_density": "kg/m"}[kind]
            out += ["", f"[materials.{name}]", f"{kind} = {q(value, unit)}", f"name = {toml_str(label[:120])}"]
        return "\n".join(out) + "\n"

    def stage_override(self, first):
        """The stage's mass override, carried on its first component."""
        f = first["fields"]
        if "stage_mass_override_kg" not in f:
            return None
        if f.get("stage_overrides_subcomponents_mass", 0) < 0.5:
            raise ValueError(f"case {self.n}: a stage mass override without subcomponents is not mapped")
        return f"override = {{ mass = {q(f['stage_mass_override_kg'], 'kg')}, subtree = true }}"

    def fin_cross_section(self, c):
        f = c["fields"]
        hit = [x for x in FIN_CROSS_SECTIONS if f.get(f"cross_section_{x}", 0) > 0.5]
        if len(hit) != 1:
            raise ValueError(f"case {self.n}: {c['name']!r} has no single cross_section_* field")
        return hit[0]

    def component(self, k, c, prev_axial):
        t = c["type"]
        f = c["fields"]
        L = c["length_m"]
        g = lambda key, d=0.0: float(f.get(key, d))  # noqa: E731
        lines = [f'type = "{t}"']
        lines.append(f"name = {toml_str(c['name'])}")
        # placement
        if c["parent"] is None:
            if prev_axial is not None:
                p = self.comps[prev_axial]
                gap = c["x_fore_m"] - (p["x_fore_m"] + p["length_m"])
                anchor = "base" if p["type"] == "nose_cone" else "aft"
                a = f'attach = {{ to = "{self.ids[prev_axial]}.{anchor}"'
                if abs(gap) > 1e-12:
                    a += f", offset = {q(gap, 'm')}"
                lines.append(a + " }")
        else:
            pk = self.index_of_parent(k)
            p = self.comps[pk]
            to_anchor = "inner" if (t not in SURFACE and p["type"] in INNER_PARENTS) else "fore"
            if t not in SURFACE and p["type"] == "body_tube":
                to_anchor = "fore"
            at = START_ANCHOR.get(t, "fore")
            off = c["x_fore_m"] - p["x_fore_m"]
            # A rail button's oracle station is its axis (L = 0): place `mid` there.
            a = f'attach = {{ to = "{self.ids[pk]}.{to_anchor}", at = "{at}", offset = {q(off, "m")}'
            spin = g("angle_offset_rad") if t != "tube_fin_set" else g("base_rotation_rad")
            if abs(spin) > 1e-12:
                a += f", spin = {q(spin, 'rad')}"
            lines.append(a + " }")
        # instances (clusters, linear lugs and buttons)
        if t == "inner_tube" and g("cluster_count", 1) > 1:
            lines.append(self.cluster(c))
        if t in ("launch_lug", "rail_button") and g("instances", 1) > 1:
            lines.append(
                f'instances = {{ count = {int(g("instances"))}, pattern = "linear", '
                f'spacing = {q(g("instance_separation_m"), "m")} }}'
            )
        if c.get("mass_override_kg") is not None:
            lines.append(f"override = {{ mass = {q(c['mass_override_kg'], 'kg')} }}")
        # material
        if "density_kgm3" in f and t not in ("parachute", "streamer", "shock_cord", "mass_component"):
            lines.append(f'material = "{self.material(c, "density", g("density_kgm3"))}"')
        if t == "parachute":
            lines.append(f'material = "{self.material(c, "surface_density", g("surface_density_kgm2"))}"')
        if t == "shock_cord":
            lines.append(f'material = "{self.material(c, "line_density", g("line_density_kgm"))}"')
        if "roughness_m" in f and (t in AXIAL or t in SURFACE):
            lines.append(f"finish = {{ roughness = {q(g('roughness_m'), 'm')} }}")
        # shape
        lines += self.shape(t, c, f, L, g)
        return lines

    def cluster(self, c):
        f = c["fields"]
        n = int(f["cluster_count"])
        pts = [(f[f"cluster{i}_y_m"], f[f"cluster{i}_z_m"]) for i in range(n)]
        d = min(math.dist(a, b) for i, a in enumerate(pts) for b in pts[i + 1 :])
        if abs(f.get("cluster_rotation_rad", 0.0)) > 1e-12:
            raise ValueError("cluster rotation is not mapped")
        return f'instances = {{ count = {n}, pattern = "cluster", preset = "{CLUSTER_PRESETS[n]}", scale = {q(d, "m")} }}'

    def shape(self, t, c, f, L, g):
        m = lambda x: q(x, "m")  # noqa: E731
        if t == "nose_cone":
            out = [f'shape = "{c["shape"]}"']
            if c["shape"] in ("ogive", "power", "parabolic", "haack"):
                out.append(f"shape_param = {num(g('shape_parameter'))}")
            out += [f"length = {m(L)}", f"od = {m(g('od_m'))}"]
            if g("filled") < 0.5:
                out.append(f"thickness = {m(g('thickness_m'))}")
            # A zero-thickness oracle shoulder carries no material (its mass is
            # the shell alone); ours would be solid, so it is left out.
            if g("shoulder_length_m") > 0 and g("shoulder_thickness_m") > 0:
                sh = f"shoulder = {{ length = {m(g('shoulder_length_m'))}, od = {m(g('shoulder_od_m'))}, thickness = {m(g('shoulder_thickness_m'))}"
                if g("shoulder_capped") > 0.5:
                    sh += ", capped = true"
                out.append(sh + " }")
            return out
        if t in ("body_tube", "coupler"):
            return [f"length = {m(L)}", f"od = {m(g('od_m'))}", f"thickness = {m(g('thickness_m'))}"]
        if t == "inner_tube":
            out = [f"length = {m(L)}", f"od = {m(g('od_m'))}", f"thickness = {m(g('thickness_m'))}"]
            if g("motor_mount") > 0.5:
                out.append("motor_mount = true")
                if g("motor_overhang_m") != 0:
                    out.append(f"overhang = {m(g('motor_overhang_m'))}")
            return out
        if t in ("centering_ring", "engine_block"):
            return [f"length = {m(L)}", f"od = {m(g('od_m'))}", f"id = {m(g('id_m'))}"]
        if t == "bulkhead":
            return [f"length = {m(L)}", f"od = {m(g('od_m'))}"]
        if t == "launch_lug":
            return [f"length = {m(L)}", f"od = {m(g('od_m'))}", f"thickness = {m(g('thickness_m'))}"]
        if t == "rail_button":
            return [
                f"od = {m(g('od_m'))}",
                f"id = {m(g('id_m'))}",
                f"height = {m(g('total_height_m'))}",
                f"base_height = {m(g('base_height_m'))}",
                f"flange_height = {m(g('flange_height_m'))}",
            ]
        if t == "parachute":
            out = [f"diameter = {m(g('diameter_m'))}", f"cd = {num(g('cd'))}"]
            if g("line_count") > 0:
                lm = self.material(
                    {"material": "shroud lines", "type": "line"}, "line_density", g("line_line_density_kgm")
                )
                out += [f"line_count = {int(g('line_count'))}", f"line_length = {m(g('line_length_m'))}", f'line_material = "{lm}"']
            out += [f"packed_length = {m(g('packed_length_m'))}", f"packed_diameter = {m(2 * g('packed_radius_m'))}"]
            return out
        if t == "shock_cord":
            return [
                f"cord_length = {m(g('cord_length_m'))}",
                f"packed_length = {m(g('packed_length_m'))}",
                f"packed_diameter = {m(2 * g('packed_radius_m'))}",
            ]
        if t == "mass_component":
            return [f"mass = {q(g('mass_kg'), 'kg')}", f"length = {m(L)}", f"od = {m(2 * g('packed_radius_m'))}"]
        if t in ("trapezoidal_fin_set", "elliptical_fin_set", "freeform_fin_set"):
            out = [f"count = {int(g('count'))}"]
            if t == "trapezoidal_fin_set":
                out += [
                    f"root_chord = {m(g('root_chord_m'))}",
                    f"tip_chord = {m(g('tip_chord_m'))}",
                    f"span = {m(g('height_m'))}",
                    f"sweep = {m(g('sweep_m'))}",
                ]
            elif t == "elliptical_fin_set":
                out += [f"root_chord = {m(g('root_chord_m'))}", f"span = {m(g('height_m'))}"]
            else:
                k, pts = 0, []
                while f"point{k}_x_m" in f:
                    pts.append(f"[{m(f[f'point{k}_x_m'])}, {m(f[f'point{k}_y_m'])}]")
                    k += 1
                out.append(f"points = [{', '.join(pts)}]")
            out.append(f"thickness = {m(g('thickness_m'))}")
            out.append(f'cross_section = "{self.fin_cross_section(c)}"')
            if abs(g("cant_rad")) > 1e-12:
                out.append(f"cant = {q(g('cant_rad'), 'rad')}")
            if g("fillet_radius_m") > 0:
                out.append(f"fillet_radius = {m(g('fillet_radius_m'))}")
            if g("tab_height_m") > 0 and g("tab_length_m") > 0:
                # The oracle's tab can end a rounding error past the root TE.
                root = g("root_chord_m")
                tab_len = min(g("tab_length_m"), root - g("tab_offset_m"))
                out.append(
                    f"tab = {{ height = {m(g('tab_height_m'))}, length = {m(tab_len)}, offset = {m(g('tab_offset_m'))} }}"
                )
            return out
        if t == "tube_fin_set":
            return [
                f"count = {int(g('count'))}",
                f"length = {m(L)}",
                f"od = {m(g('od_m'))}",
                f"id = {m(g('id_m'))}",
            ]
        raise ValueError(f"case {self.n}: unmapped type {t}")

    # ---- motor mounts ----------------------------------------------------------
    def mounts(self):
        """Indices of motor-mount components in model order."""
        return [k for k, c in enumerate(self.comps) if c["fields"].get("motor_mount", 0) > 0.5]

    # ---- config ------------------------------------------------------------------
    def config(self):
        cfg = next(c for c in self.geo["configurations"] if c["id"] == self.golden["config_id"])
        lines = [header(self.n), "", f"name = {toml_str(cfg['name'])}"]
        used = {}
        bottom = max(self.stages())
        for m in cfg["motors"]:
            rse = GENERIC / f"{m['designation']}.rse"
            if not rse.exists() or hashlib.sha256(rse.read_bytes()).hexdigest() != m["digest"]:
                raise ValueError(f"case {self.n}: {m['designation']} digest mismatch")
            cands = [k for k in self.mounts() if self.comps[k]["name"] == m["mount"]]
            k = cands[used.get(m["mount"], 0)]
            used[m["mount"]] = used.get(m["mount"], 0) + 1
            f = self.comps[k]["fields"]
            st = self.stage_of(self.comps[k])
            lines += ["", f"[motors.{self.mount_id(k)}]", f'motor = "generic:{m["designation"]}"']
            if m["delay_s"] is not None:
                lines.append(f"delay = {q(m['delay_s'], 's')}")
            if f.get("motor_ignition_event_burnout", 0) > 0.5 or (
                f.get("motor_ignition_event_automatic", 0) > 0.5 and st != bottom
            ):
                lines.append('ignition = "previous_burnout"')
            if f.get("motor_ignition_delay_s", 0) != 0:
                lines.append(f"ignition_delay = {q(f['motor_ignition_delay_s'], 's')}")
        if len(self.stages()) > 1:
            for s in self.stages()[1:]:
                first = next(c for c in self.comps if c["parent"] is None and self.stage_of(c) == s)
                f = first["fields"]
                ev = next(
                    (e for e in ("upper_ignition", "burnout", "ejection", "launch", "never") if f.get(f"stage_separation_event_{e}", 0) > 0.5),
                    None,
                )
                if ev is None:
                    raise ValueError(f"case {self.n}: stage {s} has no separation event")
                lines += ["", f"[stages.{self.stage_id(s)}]", f'separation = "{ev}"']
                if f.get("stage_separation_delay_s", 0) != 0:
                    lines.append(f"separation_delay = {q(f['stage_separation_delay_s'], 's')}")
        for k, c in enumerate(self.comps):
            if c["type"] not in ("parachute", "streamer"):
                continue
            f = c["fields"]
            ev = next(e for e in ("ejection", "apogee", "altitude", "timer") if f.get(f"deploy_event_{e}", 0) > 0.5)
            lines += ["", f"[deploy.{self.ids[k]}]", f'event = "{ev}"']
            if ev == "altitude":
                lines.append(f"altitude = {q(f['deploy_altitude_m'], 'm')}")
            if f.get("deploy_delay_s", 0) != 0:
                lines.append(f"delay = {q(f['deploy_delay_s'], 's')}")
        return cfg["id"], "\n".join(lines) + "\n"

    def mount_id(self, k):
        if self.comps[k]["type"] == "body_tube":
            return f"{self.ids[k]}_mount"
        return self.ids[k]

    def virtual_mount(self, k, c):
        """A body tube that is itself the motor mount: our mounts are inner
        tubes, so a massless-thin inner tube of the motor's length lines the
        body's aft end (fixtures/README.md)."""
        f = c["fields"]
        bore = f["od_m"] - 2 * f["thickness_m"]
        lines = [
            'type = "inner_tube"',
            f"name = {toml_str(c['name'] + ' (motor mount)')}",
            f'attach = {{ to = "{self.ids[k]}.aft", at = "aft" }}',
            f'material = "{self.material(c, "density", float(f["density_kgm3"]))}"',
            f"length = {q(f['motor_length_m'], 'm')}",
            f"od = {q(bore, 'm')}",
            'thickness = "0.001 mm"',
            "motor_mount = true",
        ]
        if f.get("motor_overhang_m", 0) != 0:
            lines.append(f"overhang = {q(f['motor_overhang_m'], 'm')}")
        return lines

    # ---- sim ---------------------------------------------------------------------
    def sim(self):
        s = next(
            x for x in self.geo["sims"] if x["name"] == self.golden["sim_name"] and x["config_id"] == self.golden["config_id"]
        )
        c = s["conditions"]
        if json.dumps(c, sort_keys=True) != json.dumps(self.golden["conditions"], sort_keys=True):
            raise ValueError(f"case {self.n}: geometry and golden conditions differ")
        lines = [
            header(self.n),
            "",
            f"name = {toml_str(s['name'])}",
            f"config = {toml_str(s['config_id'])}",
        ]
        if "gravity" in c:
            gm = c["gravity"]
            if gm["model"] == "wgs84":
                lines.append('gravity = { model = "wgs84" }')
            else:
                lines.append(f'gravity = {{ model = "constant", g = {q(gm["g_ms2"], "m/s^2")} }}')
        if "launch_into_wind" in c:
            lines.append(f"launch_into_wind = {'true' if c['launch_into_wind'] else 'false'}")
        lines += [
            "",
            "[launch]",
            f"rail_length = {q(c['rail_length_m'], 'm')}",
            f"rod_angle = {q(c['rod_angle_deg'], 'deg')}",
            f"rod_direction = {q(c['rod_direction_deg'], 'deg')}",
            f"altitude = {q(c['site_altitude_m'], 'm')}",
            f"latitude = {q(c['latitude_deg'], 'deg')}",
            f"longitude = {q(c['longitude_deg'], 'deg')}",
            f"geodetic = {toml_str(c['geodetic'])}",
            "",
            "[atmosphere]",
            f"model = {toml_str(c['atmosphere'])}",
            f"base_temperature = {q(c['base_temperature_k'], 'K')}",
            f"base_pressure = {q(c['base_pressure_pa'], 'Pa')}",
            "",
            "[wind]",
            f"speed = {q(c['wind_speed_ms'], 'm/s')}",
            f"direction = {q(c['wind_direction_deg'], 'deg')}",
            f"turbulence = {num(c['wind_turbulence'])}",
            "",
            "[integrator]",
            f"method = {toml_str(c['integrator'])}",
            f"dt = {q(c['time_step_s'], 's')}",
        ]
        return f"sims/{slug(s['name'])}.rw.toml", "\n".join(lines) + "\n"

    def files(self):
        rocket = self.rocket()
        cid, cfg = self.config()
        sp, sim = self.sim()
        manifest = "\n".join(
            [header(self.n), "", "format = 1", f"name = {toml_str(self.geo['name'])}", f"default_config = {toml_str(cid)}", ""]
        )
        return {
            "rocket.rw.toml": rocket,
            f"configs/{cid}.rw.toml": cfg,
            sp: sim,
            "rocketwright.toml": manifest,
        }


def main(argv):
    check = "--check" in argv
    cases = [int(a) for a in argv if a.isdigit()] or [2, 3, 4, 5, 6, 7]
    bad = 0
    for n in cases:
        d = ROOT / "fixtures" / f"case{n}"
        files = Case(n).files()
        for rel, text in files.items():
            p = d / rel
            if check:
                if not p.exists() or p.read_text() != text:
                    print(f"fixtures/case{n}: {rel} differs (run scripts/fixtures/oracle_case.py)", file=sys.stderr)
                    bad += 1
            else:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(text)
        if check:
            for sub in ("configs", "sims"):
                for p in sorted((d / sub).glob("*")) if (d / sub).exists() else []:
                    if f"{sub}/{p.name}" not in files:
                        print(f"fixtures/case{n}: stale {sub}/{p.name}", file=sys.stderr)
                        bad += 1
        else:
            print(f"fixtures/case{n}: wrote {len(files)} files")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
